#!/usr/bin/env python3
import sys; sys.stdout.reconfigure(encoding="utf8")
"""Build engine/revision-es.js (the shared Spanish dictionary for revision sites) from tools/es-src.
Sources: <name>.keys.json (list of English strings, from tools/save-keys.py) + <name>.*.txt (lines 'N|Spanish' where N indexes that list)
plus extra.txt (lines 'English|||Spanish'). Usage: python tools/build-es.py [--missing keysfile.json ...]"""
import json, glob, os, sys, re
D = os.path.join(os.path.dirname(__file__), "es-src")
dic = {}
for kf in sorted(glob.glob(os.path.join(D, "*.keys.json"))):
    name = os.path.basename(kf)[:-len(".keys.json")]
    keys = json.load(open(kf, encoding="utf8"))
    for tf in sorted(glob.glob(os.path.join(D, name + ".*.txt"))) + sorted(glob.glob(os.path.join(D, name + ".es.txt"))):
        for line in open(tf, encoding="utf8"):
            m = re.match(r"^(\d+)\|(.*)$", line.rstrip("\n"))
            if m and int(m.group(1)) < len(keys): dic[keys[int(m.group(1))]] = m.group(2)
ex = os.path.join(D, "extra.txt")
if os.path.exists(ex):
    for line in open(ex, encoding="utf8"):
        if "|||" in line: a, b = line.rstrip("\n").split("|||", 1); dic[a] = b
if "--missing" in sys.argv:
    for kf in sys.argv[sys.argv.index("--missing") + 1:]:
        allk = json.load(open(kf, encoding="utf8")); miss = [(i, k) for i, k in enumerate(allk) if k not in dic]
        for i, k in miss: print(f"{i}|{k}")
        print(f"## {len(miss)} missing from {os.path.basename(kf)}", file=sys.stderr)
else:
    out = os.path.join(os.path.dirname(__file__), "..", "engine", "revision-es.js")
    open(out, "w", encoding="utf8").write("/* Generated by tools/build-es.py. Do not edit by hand. */\nexport const ES = " + json.dumps(dic, ensure_ascii=False, indent=0) + ";\n")
    print(len(dic), "entries")
